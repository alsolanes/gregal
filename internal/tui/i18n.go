package tui

// Idioma del TUI. Mateix criteri que a la finestra (internal/web/app/i18n.js):
// el codi, els comentaris i els tests segueixen en català —això no es toca—
// però el que es llegeix a la pantalla no ha d'obligar ningú a saber-lo.
//
// Les claus són curtes i estables, no la frase catalana: si la clau fos la
// frase, corregir-hi una coma trencaria l'anglès. i18n_test.go comprova que
// els dos diccionaris tenen exactament les mateixes claus, que és l'única
// manera que això no es quedi a mitges.
//
// Una variable de paquet i prou: el TUI és un procés amb una sessió i
// l'idioma es fixa una vegada a l'arrencada, des de cfg.Lang().

var idiomaActual = "en"

// SetIdioma fixa l'idioma de la interfície ("ca" o "en"). Qualsevol altra
// cosa deixa el català.
func SetIdioma(l string) {
	if _, ok := diccionaris[l]; ok {
		idiomaActual = l
	}
}

// T tradueix una clau. Sense traducció, torna el català abans que la clau
// crua: val més una paraula en l'idioma que no toca que «barra.scroll» a la
// pantalla.
func T(clau string) string {
	if d, ok := diccionaris[idiomaActual]; ok {
		if s, hi := d[clau]; hi {
			return s
		}
	}
	if s, hi := catala[clau]; hi {
		return s
	}
	return clau
}

