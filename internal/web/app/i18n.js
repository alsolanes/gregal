const DICCIONARIS = { ca: CA, en: EN };
export const CLAUS = { ca: CA, en: EN }; // per als tests

const CLAU_DESAT = 'gregal_idioma';

// idioma actual. «sistema» no hi és a posta: l'idioma també decideix en
// quina llengua respon l'agent, i endevinar-ho pel navegador voldria dir
// que la mateixa pregunta et respon diferent segons on obris la finestra.
// perDefecte és el que diu el config del servidor. La tria del navegador
// mana per sobre —és més recent i és teva—, però si aquest navegador no
// n'ha triat mai cap, el que val és el config: amb «lang: en» al fitxer,
// el TUI sortia en anglès i la finestra en català, que no té cap sentit.
// El config del servidor mana (lang: ca a casa nostra); si el navegador
// no ha triat mai res, el català és el punt de partida.
let perDefecte = 'ca';

export function idioma() {
  try {
    const v = localStorage.getItem(CLAU_DESAT);
    if (v && DICCIONARIS[v]) return v;
  } catch (e) {}
  return perDefecte;
}

// defineixPerDefecte rep l'idioma del servidor. Si el navegador no n'ha
// triat cap i és diferent del que hi ha pintat, torna a pintar.
export function defineixPerDefecte(l) {
  if (!DICCIONARIS[l] || l === perDefecte) return;
  let triat = null;
  try { triat = localStorage.getItem(CLAU_DESAT); } catch (e) {}
  perDefecte = l;
  if (!triat || !DICCIONARIS[triat]) aplica();
}

export function t(clau, sino) {
  const d = DICCIONARIS[idioma()] || CA;
  if (clau in d) return d[clau];
  // Sense traducció, el català abans que la clau crua: val més una paraula
  // en l'idioma que no toca que «prefs.verify» a la pantalla.
  if (clau in CA) return CA[clau];
  return sino == null ? clau : sino;
}

// aplica tradueix el que ja és a la pàgina. Els atributs van per separat
// perquè un botó amb icona té el text al title i a l'aria-label, no dins.
export function aplica(arrel) {
  const r = arrel || document;
  r.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  r.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  for (const [sel, prop, attr] of [
    ['[data-i18n-title]', 'i18nTitle', 'title'],
    ['[data-i18n-ph]', 'i18nPh', 'placeholder'],
    ['[data-i18n-aria]', 'i18nAria', 'aria-label'],
  ]) {
    r.querySelectorAll(sel).forEach(el => el.setAttribute(attr, t(el.dataset[prop])));
  }
  document.documentElement.lang = idioma();
  // Els data-i18n es refan sols; el text que es construeix des de JS —la
  // llista de documents de l'Office, per exemple— no, i es quedava en
  // l'idioma que hi havia quan es va pintar. Qui en tingui, que escolti.
  document.dispatchEvent(new CustomEvent('gregal:idioma', { detail: idioma() }));
}

// posa canvia l'idioma: a la pantalla i al servidor, perquè les respostes
// de l'agent el segueixin. Si el servidor no el pot desar, no es canvia
// res: val més seguir en català que tenir la finestra i l'agent discutint.
export async function posa(codi, api) {
  if (!DICCIONARIS[codi]) return false;
  if (api) {
    const r = await api('/api/lang', { method: 'POST', body: JSON.stringify({ lang: codi }) });
    if (!r.ok) throw new Error((await r.text()).trim() || ('HTTP ' + r.status));
  }
  try { localStorage.setItem(CLAU_DESAT, codi); } catch (e) {}
  aplica();
  return true;
}
